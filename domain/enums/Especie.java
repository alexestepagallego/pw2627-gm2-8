package es.uco.pw.refugio.domain.enums;

/**
 * Especies de animales que acoge el refugio. Se usa tanto para clasificar a los animales
 * como para indicar el tipo de animal que aloja cada recinto.
 */
public enum Especie {

    /** Perro. */
    PERRO,

    /** Gato. */
    GATO,

    /** Conejo. */
    CONEJO,

    /** Hurón. */
    HURON,

    /** Ave. */
    AVE,

    /** Cualquier otra especie no contemplada. */
    OTRO
}
